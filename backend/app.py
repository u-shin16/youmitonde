def to_account(entry):
    urlname = entry.get("urlname")
    return {
        "key": entry.get("key"),
        "urlname": urlname,
        "name": entry.get("nickname") or entry.get("name") or urlname,
        # v2 (/api/v2/creators/.../followers) uses camelCase; v3
        # (/api/v3/users/.../followers) uses snake_case for the same field.
        "profileImage": entry.get("userProfileImagePath") or entry.get("user_profile_image_path"),
        "noteUrl": f"https://note.com/{urlname}",
    }


def normalized_urlname(entry):
    urlname = entry.get("urlname")
    if not urlname:
        return None
    return str(urlname).strip().lower()


def account_identity_values(entry):
    identities = set()
    for field in ("key", "id"):
        value = entry.get(field)
        if value:
            identities.add((field, str(value)))

    urlname = normalized_urlname(entry)
    if urlname:
        identities.add(("urlname", urlname))

    return identities


def account_identities(entries):
    identities = set()
    for entry in entries:
        identities.update(account_identity_values(entry))
    return identities


def is_known_account(entry, identities):
    return not account_identity_values(entry).isdisjoint(identities)


def parse_check_request():
    if request.method == "POST":
        payload = request.get_json(silent=True) or {}
        return normalize_username(payload.get("username", "")), (payload.get("cookieHeader") or "").strip()

    return normalize_username(request.args.get("username", "")), ""


def cookie_matches_creator(session, urlname, cookie_header):
    if not cookie_header:
        return False

    try:
        creator = fetch_creator(session, urlname, headers=request_headers(cookie_header))
    except (NoteApiError, requests.RequestException):
        return False

    return bool(creator and creator.get("isMyself"))


# 詳細を引けなかったアカウントを表す印。keep_accountを評価できていないので、
# 残すことも捨てることもできない。
_UNKNOWN_ACCOUNT = object()


def entry_relation_flag(entry, flag_names):
    """一覧の項目に入っている関係フラグ（相互かどうか）を読む。

    値が入っていなければNone。認証なしで取得した一覧では全員Falseになるため、
    ここが使えるのはログイン済みの取得だけ。
    """
    for name in flag_names:
        value = entry.get(name)
        if isinstance(value, bool):
            return value
    return None


def refine_accounts_with_authenticated_state(
    session, entries, cookie_header, keep_account, flag_names=()
):
    """keep_accountがTrueのアカウントだけ残す。返り値は (残った件数, 確認できなかった件数)。

    詳細は1人ずつ問い合わせる必要があり、フォロー中2,445人＋フォロワー2,424人の
    アカウントでは約4,900回になる。note.comの前段CloudFrontはIP単位で数を見ており、
    ここで枠を使い切ると後続が弾かれて「確認できませんでした」が大量に出ていた。

    ところが一覧の項目自体に、ログイン中の本人から見た関係（相手が自分を
    フォローしているか／自分が相手をフォローしているか）が入っている。
    note.com自身の一覧ページも、この値で「フォローされています」を出している。
    そこで一覧の値で候補を絞り、候補になった人だけ個別に確認する。
    問い合わせ回数が数十回まで減り、確認できない人がほとんど出なくなる。

    一覧の値をそのまま信じると、値の意味を読み違えていた場合に相互フォローの
    相手を切ることになる。そこで「一覧では相互」とされた人からいくらか抜き取って
    確認し、1人でも食い違ったら絞り込みをやめて全員を個別に確認する。
    """
    if not entries:
        return [], 0

    headers = request_headers(cookie_header)

    def verify(targets):
        # 個別に確認する。確認できなかった人は一覧から外し、件数だけ返す。
        # note.comは403/429を返しやすく、確認できていない人を混ぜると
        # 相互フォローの相手を切ることになるため。
        def worker(entry):
            try:
                detail = fetch_creator(session, entry.get("urlname"), headers=headers)
            except (NoteApiError, requests.RequestException):
                return _UNKNOWN_ACCOUNT

            if detail is None:
                # 404。退会・削除済みなので、判定できなかったのとは区別して落とす。
                return None

            return to_account(entry) if keep_account(detail) else None

        kept = []
        unknown = 0
        with ThreadPoolExecutor(max_workers=AUTH_VERIFY_WORKERS) as executor:
            futures = [executor.submit(worker, entry) for entry in targets]
            for future in as_completed(futures):
                result = future.result()
                if result is _UNKNOWN_ACCOUNT:
                    unknown += 1
                elif result:
                    kept.append(result)
        return kept, unknown

    candidates = []
    assumed_mutual = []
    for entry in entries:
        flag = entry_relation_flag(entry, flag_names)
        if flag is True:
            assumed_mutual.append(entry)
        else:
            # Falseは候補。Noneは一覧に情報がないので、絞り込まず個別に確認する。
            candidates.append(entry)

    if assumed_mutual and not prescreen_agrees(assumed_mutual, verify):
        app.logger.info("一覧の関係フラグが食い違ったため、全員を個別に確認する")
        candidates = list(entries)
        assumed_mutual = []

    app.logger.info(
        "個別確認: %s人中%s人に絞り込み（一覧で相互とみなした%s人は問い合わせない）",
        len(entries),
        len(candidates),
        len(assumed_mutual),
    )

    refined, unknown = verify(candidates)
    refined.sort(key=lambda account: account["name"])
    return refined, unknown


def prescreen_agrees(assumed_mutual, verify):
    """「一覧では相互」とされた人を抜き取って確認し、食い違いがないか見る。"""
    step = max(1, len(assumed_mutual) // PRESCREEN_SAMPLE_SIZE)
    sample = assumed_mutual[::step][:PRESCREEN_SAMPLE_SIZE]
    kept, _unknown = verify(sample)
    return not kept


@app.get("/api/creator/<urlname>")
def creator_detail(urlname):
    session = requests.Session()
    try:
        creator = fetch_creator(session, urlname)
    except NoteApiError as exc:
        return note_error_response(exc)
    except requests.RequestException:
        return jsonify({"error": "note.comへの接続に失敗しました。時間をおいてもう一度お試しください"}), 502

    if creator is None:
        return jsonify({"error": f"ユーザー「{urlname}」が見つかりませんでした"}), 404

    return jsonify(
        {
            "urlname": creator.get("urlname"),
            "name": creator.get("nickname"),
            "profile": creator.get("profile"),
            "profileImage": creator.get("profileImageUrl"),
            "followingCount": creator.get("followingCount") or 0,
            "followerCount": creator.get("followerCount") or 0,
            "noteCount": creator.get("noteCount") or 0,
        }
    )


@app.route("/api/check", methods=["GET", "POST"])
def check():
    urlname, cookie_header = parse_check_request()
    if not urlname:
        return jsonify({"error": "noteのユーザー名を入力してください"}), 400
    if not cookie_header:
        return jsonify({"error": "アカウントチェックにはnote.comのCookie文字列が必要です"}), 400

    session = requests.Session()
    try:
        creator = fetch_creator(session, urlname)
        if creator is None:
            return jsonify({"error": f"ユーザー「{urlname}」が見つかりませんでした"}), 404

        authenticated_check = cookie_matches_creator(session, urlname, cookie_header)
        creator_key = creator.get("key")
        if authenticated_check and creator_key:
            # The public v2/creators endpoint has its own undocumented item
            # cap that the `per` param doesn't lift. When checking your own
            # account (the common case here), note.com's own web UI instead
            # calls this authenticated v3 endpoint, which returns the real,
            # uncapped total.
            followings, followings_total = fetch_all_follows_v3(session, creator_key, "followings", cookie_header)
            followers, followers_total = fetch_all_follows_v3(session, creator_key, "followers", cookie_header)
        else:
            followings, followings_total = fetch_all_follows(session, urlname, "followings")
            followers, followers_total = fetch_all_follows(session, urlname, "followers")
    except NoteApiError as exc:
        return note_error_response(exc)
    except requests.RequestException:
        return jsonify({"error": "note.comへの接続に失敗しました。時間をおいてもう一度お試しください"}), 502

    follower_identities = account_identities(followers)
    follower_count = creator.get("followerCount") or 0
    following_count = creator.get("followingCount") or 0
    # 上限判定は2種類ある。どちらか一方でも当てはまれば「全部は見られていない」。
    #   (1) note.comが申告する総数そのものが頭打ちになっている（公開v2の~1000件上限）
    #   (2) 総数は正しいのに、一覧が途中で打ち切られて取り切れていない
    # (2)を見ていなかったため、認証済みv3が「総数1629」と正しく返しつつ実際には
    # 1000件しか返さないケースを「全部取れた」と誤判定し、1000件中の結果を
    # 1629件中の結果であるかのように表示していた。
    followers_capped = (follower_count > 0 and follower_count > followers_total) or (
        followers_total > 0 and len(followers) < followers_total
    )
    followings_capped = (following_count > 0 and following_count > followings_total) or (
        followings_total > 0 and len(followings) < followings_total
    )
    auth_warning = None
    to_follow_back_unavailable_reason = None

    not_following_back_scope = None
    to_follow_back_scope = None
    # 詳細を引けず判定できなかった件数。どの分岐を通っても値が入るようにしておく。
    not_following_back_unknown = 0
    to_follow_back_unknown = 0
    if authenticated_check:
        # 各アカウントのisFollowedを直接見る方式。フォロワー一覧の取得状況に
        # 依存しないため、フォロー中一覧が途中までしか取れていない場合でも、
        # 取れた範囲については正しい結果になる。範囲だけ利用者に伝える。
        not_following_back, not_following_back_unknown = refine_accounts_with_authenticated_state(
            session,
            followings,
            cookie_header,
            lambda detail: not detail.get("isFollowed"),
            flag_names=("is_followed", "isFollowed"),
        )
        not_following_back_reliable = not followings_capped
        if followings_capped:
            not_following_back_scope = (
                f"フォロー中{following_count:,}人のうち、note.com側の上限で確認できた"
                f"{len(followings):,}人の中での結果です。"
            )
    elif followers_capped:
        not_following_back = []
        not_following_back_reliable = False
    else:
        not_following_back = [
            to_account(f) for f in followings if not is_known_account(f, follower_identities)
        ]
        not_following_back.sort(key=lambda account: account["name"])
        not_following_back_reliable = True

    if authenticated_check:
        # 片思い側と同じ考え方。各アカウントのisFollowingを直接見る方式なので、
        # フォロワー一覧が途中までしか取れていなくても、取れた範囲の結果は正しい。
        # 以前はfollowers_cappedで丸ごと非表示にしていたため、フォロワーが
        # 1,000人を超えた時点からフォロー返し候補が一切出なくなっていた。
        # 上限は超えられないので、範囲を伝えたうえで出す。
        to_follow_back, to_follow_back_unknown = refine_accounts_with_authenticated_state(
            session,
            followers,
            cookie_header,
            lambda detail: not detail.get("isFollowing"),
            flag_names=("is_following", "isFollowing"),
        )
        if followers_capped:
            to_follow_back_scope = (
                f"フォロワー{follower_count:,}人のうち、note.com側の上限で確認できた"
                f"{len(followers):,}人の中での結果です。"
            )
    elif cookie_header and not authenticated_check:
        to_follow_back = []
        auth_warning = "Cookieのログインアカウントとチェック対象が一致しなかったため、フォロー済みかどうかの追加確認は使いませんでした。"
        to_follow_back_unavailable_reason = auth_warning
    else:
        to_follow_back = []
        to_follow_back_unavailable_reason = "フォロー返し候補は、Cookieを貼ってログイン中の本人として確認できた場合だけ表示します。Cookieを入力して再チェックしてください。"

    capped = followers_capped or followings_capped

    # 画面の数字（note.comのプロフィールカウンター）と、実際に突き合わせた件数の
    # ズレを追うための記録。プロフィールの数字と、こちらが取得できた一覧の件数と、
    # 片思い判定の結果が別ソースになるため、食い違ったときはここを見る。
    app.logger.info(
        "check urlname=%s auth=%s プロフィール(following=%s follower=%s) "
        "取得(following=%s follower=%s) total(following=%s follower=%s) "
        "capped(following=%s follower=%s) 片思い=%s フォロー返し候補=%s",
        urlname,
        authenticated_check,
        following_count,
        follower_count,
        len(followings),
        len(followers),
        followings_total,
        followers_total,
        followings_capped,
        followers_capped,
        len(not_following_back),
        len(to_follow_back),
    )
    if not_following_back_unknown or to_follow_back_unknown:
        # 403/429で判定できなかった分。多いときは一覧が実態より少なく見える。
        app.logger.info(
            "check urlname=%s 確認できず除外 片思い=%s フォロー返し候補=%s",
            urlname,
            not_following_back_unknown,
            to_follow_back_unknown,
        )

    return jsonify(
        {
            "creator": {
                "urlname": creator.get("urlname"),
                "name": creator.get("nickname"),
                "profileImage": creator.get("profileImageUrl"),
                "followingCount": following_count,
                "followerCount": follower_count,
            },
            "checkedFollowingCount": len(followings),
            "checkedFollowerCount": len(followers),
            "notFollowingBack": not_following_back,
            "toFollowBack": to_follow_back,
            "notFollowingBackUnknownCount": not_following_back_unknown,
            "toFollowBackUnknownCount": to_follow_back_unknown,
            "notFollowingBackReliable": not_following_back_reliable,
            "notFollowingBackScope": not_following_back_scope,
            "toFollowBackReliable": authenticated_check,
            "toFollowBackScope": to_follow_back_scope,
            "toFollowBackUnavailableReason": to_follow_back_unavailable_reason,
            "authenticatedCheck": authenticated_check,
            "authWarning": auth_warning,
            "capped": capped,
        }
    )


def fetch_creator_contents(session, urlname, kind, page):
    resp = request_with_retries(
        session, f"{NOTE_API_BASE}/{urlname}/contents", params={"kind": kind, "page": page}
    )
    raise_for_transient_status(resp)
    if resp.status_code != 200:
        raise NoteApiError(f"記事一覧の取得に失敗しました（status {resp.status_code}）")
    data = note_json(resp, "contents").get("data")
    if not isinstance(data, dict):
        return [], True
    return data.get("contents", []), bool(data.get("isLastPage"))


def fetch_note_likes(session, note_key, page):
    resp = request_with_retries(
        session, f"{NOTE_NOTE_API_BASE}/{note_key}/likes", params={"page": page}
    )
    raise_for_transient_status(resp)
    if resp.status_code != 200:
        raise NoteApiError(f"スキ一覧の取得に失敗しました（status {resp.status_code}）")
    data = note_json(resp, "likes").get("data")
    if not isinstance(data, dict):
        return []
    return data.get("likes", [])


def collect_contents(session, urlname, kind, max_pages):
    contents = []
    for page in range(1, max_pages + 1):
        items, is_last = fetch_creator_contents(session, urlname, kind, page)
        if not items:
            break
        contents.extend(items)
        if is_last:
            break
    return contents


def collect_note_likers(session, note_key):
    likers = []
    for page in range(1, DEEP_SEARCH_MAX_LIKE_PAGES_PER_NOTE + 1):
        likes = fetch_note_likes(session, note_key, page)
        if not likes:
            break
        likers.extend(like.get("user") or {} for like in likes)
        # note.comは1ページ50件で返す。それを下回ったら最後のページ。
        if len(likes) < 50:
            break
    return likers


def collect_interaction_candidates(session, urlname):
    """スキのやりとりからnote IDの候補を集める。

    フォロー一覧のAPIは20人×50ページ＝1,000人で打ち止めで、読み出し位置を
    指定する手段も無いため、1,001人目から先は取得できない（note.com自身の
    一覧ページも同じ作りで、同じところで止まる）。

    ところがスキの一覧（/v3/notes/{key}/likes）にはこの上限が無く、51ページ目
    以降も返ってくる。スキのやりとりがあった人に限られるものの、1,000人より
    奥にいる人をここから拾える。拾った人が実際にどういう関係かは、1人ずつ
    確認しないと分からないので、ここで返すのはあくまで候補。
    """
    candidates = {}

    def remember(user):
        name = user.get("urlname")
        if not name or name == urlname or name in candidates:
            return
        candidates[name] = {
            "key": user.get("key"),
            "urlname": name,
            "name": user.get("nickname") or user.get("name") or name,
            "profileImage": user.get("userProfileImagePath") or user.get("user_profile_image_path"),
            "noteUrl": f"https://note.com/{name}",
        }

    # 自分がスキした記事の著者
    for content in collect_contents(session, urlname, "likes", DEEP_SEARCH_MAX_LIKED_PAGES):
        remember(content.get("user") or {})

    # 自分の記事にスキしてくれた人
    notes = collect_contents(session, urlname, "note", DEEP_SEARCH_MAX_NOTE_PAGES)
    note_keys = [n.get("key") for n in notes if n.get("key") and (n.get("likeCount") or 0) > 0]

    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as executor:
        futures = [executor.submit(collect_note_likers, session, key) for key in note_keys]
        for future in as_completed(futures):
            for user in future.result():
                remember(user)

    return candidates, len(notes)


@app.post("/api/deep-candidates")
def deep_candidates():
    """1,000人の壁の先にいる人の「候補」を返す。

    関係の判定はここではやらない。1人ずつnote.comへ問い合わせる必要があり、
    サーバーの1つのIPからまとめて投げるとnote.com前段のCloudFrontに
    ブロックされるため、拡張機能（利用者自身のChrome）側で行う。
    """
    payload = request.get_json(silent=True) or {}
    urlname = normalize_username(payload.get("username", ""))
    cookie_header = (payload.get("cookieHeader") or "").strip()
    if not urlname:
        return jsonify({"error": "noteのユーザー名を入力してください"}), 400

    session = requests.Session()
    try:
        creator = fetch_creator(session, urlname, headers=request_headers(cookie_header))
        if creator is None:
            return jsonify({"error": "アカウントが見つかりませんでした"}), 404

        candidates, note_count = collect_interaction_candidates(session, urlname)

        # すでに一覧に出ている人は候補から外す。壁の先にいる人だけ残す。
        creator_key = creator.get("key")
        visible = set()
        for kind in ("followings", "followers"):
            follows, _total = fetch_all_follows_v3(session, creator_key, kind, cookie_header)
            visible.update(normalized_urlname(f) for f in follows)
    except NoteApiError as exc:
        return note_error_response(exc)
    except requests.RequestException:
        return jsonify({"error": "note.comへの接続に失敗しました。時間をおいてもう一度お試しください"}), 502

    hidden = [
        account
        for name, account in candidates.items()
        if str(name).strip().lower() not in visible
    ]
    hidden.sort(key=lambda account: account["name"])

    app.logger.info(
        "壁の先の候補: 記事%s本から候補%s人、うち一覧に出ていない%s人",
        note_count,
        len(candidates),
        len(hidden),
    )

    return jsonify(
        {
            "candidates": hidden[:DEEP_SEARCH_MAX_CANDIDATES],
            "scannedNoteCount": note_count,
            "collectedCount": len(candidates),
            "alreadyVisibleCount": len(candidates) - len(hidden),
        }
    )


def parse_follow_action_request():
    payload = request.get_json(silent=True) or {}
    cookie_header = (payload.get("cookieHeader") or "").strip()
    targets = payload.get("targets") or []

    if not cookie_header:
        return None, None, (jsonify({"error": "note.comのCookie文字列を入力してください"}), 400)
    if not targets:
        return None, None, (jsonify({"error": "対象が選択されていません"}), 400)
    if len(targets) > MAX_FOLLOW_ACTION_TARGETS:
        return None, None, (
            jsonify({"error": f"一度に処理できるのは{MAX_FOLLOW_ACTION_TARGETS}件までです"}),
            400,
        )
    return cookie_header, targets, None


def verify_action_applied(session, cookie_header, urlname, method):
    # note.com's follow/unfollow endpoint sometimes answers a processed request
    # with an error-looking status (rate limiting, transient 5xx). Before
    # reporting those as failures, check whether the follow state actually
    # changed as intended.
    if not urlname:
        return False
    try:
        detail = fetch_creator(session, urlname, headers=request_headers(cookie_header))
    except (NoteApiError, requests.RequestException):
        return False
    if detail is None:
        return False
    expected_following = method == "POST"
    return detail.get("isFollowing") == expected_following


def perform_follow_action(cookie_header, targets, method):
    # NOTE: /api/v3/users/{key}/following is not officially documented by note.com.
    # Reverse-engineered from a live captured request: the path segment is the
    # creator's hex "key" (not the numeric "id"), auth is the full note.com
    # cookie jar (session cookie + note_gql_auth_token together), and
    # X-Requested-With: XMLHttpRequest is required or note.com returns 422.
    session = requests.Session()
    headers = {
        **REQUEST_HEADERS,
        "Referer": "https://note.com/",
        "Origin": "https://note.com",
        "X-Requested-With": "XMLHttpRequest",
        "Cookie": cookie_header,
    }

    results = []
    for index, target in enumerate(targets):
        key = target.get("key")
        urlname = target.get("urlname")

        if index > 0:
            time.sleep(FOLLOW_ACTION_DELAY_SECONDS)

        if not key:
            results.append({"urlname": urlname, "success": False, "error": "keyが取得できませんでした"})
            continue

        url = f"{NOTE_FOLLOW_API_BASE}/{key}/following"
        resp = None
        error = None

        try:
            resp = session.request(method, url, headers=headers, timeout=REQUEST_TIMEOUT)
        except requests.RequestException:
            error = "note.comへの接続に失敗しました"

        if error:
            results.append({"urlname": urlname, "success": False, "error": error})
            continue

        if resp.status_code == 429:
            rate_limit_error = "note.comのレート制限に達しました。数分〜数十分単位のクールダウンが必要な場合があるので、5〜10分ほど間隔を空けて件数を減らして試してください"
            if verify_action_applied(session, cookie_header, urlname, method):
                results.append({"urlname": urlname, "success": True, "error": None})
            else:
                results.append({"urlname": urlname, "success": False, "error": rate_limit_error})
            # Once rate-limited, every remaining target will fail the same way.
            # Stop immediately instead of still waiting+trying each one.
            for remaining in targets[index + 1 :]:
                results.append(
                    {"urlname": remaining.get("urlname"), "success": False, "error": rate_limit_error}
                )
            break

        if resp.status_code == 403 and is_cloudfront_block_response(resp):
            # note.com sits behind CloudFront, which starts hard-blocking this
            # server's requests (a generic CloudFront error page, not a
            # note.com-level response) once too many requests land in a short
            # window -- observed after ~20 sequential follow/unfollow calls.
            # Every remaining target would fail the same way, so stop instead
            # of hammering an endpoint that's already blocking us (which only
            # prolongs the block) and dumping the same raw HTML into every row.
            block_error = (
                "note.com側のアクセス制限に達したため、これ以降の処理を中断しました。"
                "30分〜1時間ほど間隔を空けてから、件数を減らして再度お試しください。"
            )
            results.append({"urlname": urlname, "success": False, "error": block_error})
            for remaining in targets[index + 1 :]:
                results.append({"urlname": remaining.get("urlname"), "success": False, "error": block_error})
            break

        if resp.status_code in (401, 403):
            results.append(
                {"urlname": urlname, "success": False, "error": "認証に失敗しました。Cookieが正しいか確認してください"}
            )
            continue

        ok = resp.status_code in (200, 201, 204)
        if not ok:
            ok = verify_action_applied(session, cookie_header, urlname, method)
        results.append(
            {
                "urlname": urlname,
                "success": ok,
                "error": None if ok else f"note.comがstatus {resp.status_code}を返しました",
            }
        )

    return results


@app.post("/api/unfollow")
def unfollow():
    cookie_header, targets, error = parse_follow_action_request()
    if error:
        return error
    return jsonify({"results": perform_follow_action(cookie_header, targets, "DELETE")})


